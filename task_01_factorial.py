# Задание 1. Рекурсивное вычисление факториала числа.


def factorial(n):
    """Возвращает n! с помощью рекурсии."""
    if n == 0 or n == 1:  # Базовый случай.
        return 1
    return n * factorial(n - 1)  # Рекурсивный случай.


number = int(input("Введите неотрицательное целое число n: "))

if number < 0:
    print("Ошибка: факториал отрицательного числа не определён.")
else:
    print(f"Факториал числа {number} равен {factorial(number)}")
